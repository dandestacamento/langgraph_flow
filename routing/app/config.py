# 5, not 3: a compound question needing evidence from 2 chapters within a
# subtopic (Level 6) can have the top-3 slots monopolized by the single
# most lexically-similar chapter, starving out an equally-relevant second
# chapter - see instructions/Langgraph_routing/4_to_5_obserability.md's
# washing-machine E21 example. Verified empirically: top_k=3 missed the
# WM-500's warranty-terms chapter entirely for "what does E21 mean ... and
# is it covered under warranty?"; top_k=5 covered both chapters (and
# generalized across 9 other same-subtopic compound questions tested) -
# since every subtopic here only has 3-4 chapters, 5 chunks reliably spans
# all of them without needing per-chapter-guaranteed retrieval logic.
RETRIEVAL_TOP_K = 5

